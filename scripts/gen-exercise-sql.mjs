// Generates the exercise-library migration from src/data/exercises.js so the
// database and the offline app always share one source of truth.
//   node scripts/gen-exercise-sql.mjs
import { writeFileSync } from 'node:fs';
import { EXERCISES } from '../src/data/exercises.js';

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const rows = EXERCISES.map((e) =>
  `  (${q(e.id)}, ${q(e.name)}, ${q(e.category)}, ${q(e.description)}, ${q(JSON.stringify(e.tips))}::jsonb)`);

const sql = `-- GENERATED by scripts/gen-exercise-sql.mjs from src/data/exercises.js. Do not edit by hand.
-- Core exercise library (coach_id = null). Re-running updates names, descriptions and tips.
insert into public.exercises (id, name, category, description, tips) values
${rows.join(',\n')}
on conflict (id) do update set name = excluded.name, category = excluded.category,
  description = excluded.description, tips = excluded.tips;
`;
const out = new URL('../supabase/migrations/20261020120100_exercise_library.sql', import.meta.url);
writeFileSync(out, sql);
console.log(`wrote ${EXERCISES.length} exercises → ${out.pathname}`);
